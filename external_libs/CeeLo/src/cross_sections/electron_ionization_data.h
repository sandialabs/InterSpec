#pragma once

/// @file electron_ionization_data.h
/// @brief K-shell electron-impact ionization cross sections (EPICS2023 EEDL).
///
/// Generated by tools/prepare_cross_sections/generate_eedl_ionization.py from
/// the EEDL K-subshell electroionization cross section (MF=23 MT=534), for
/// Z = 1..kMaxElectronTableZ at EEDL's native nodes from threshold (the K
/// binding energy) through the first node at or above 20 MeV. Used by the
/// electron walks to emit electron-impact ionization K x-rays.

#include <cstddef>
#include <cstdint>

namespace ceelo {
namespace eedl_ionization {

constexpr std::size_t kElementCount = 92;  ///< Z = 1..92 (electron-table domain)

/// One element's K-shell ionization cross section: num_nodes points, the first
/// at threshold with zero cross section. Linear-linear between nodes, as EEDL
/// declares; zero below threshold.
struct KShellIonization {
    uint8_t num_nodes;
    const float* energy_keV;   ///< electron kinetic energy (keV), ascending
    const float* sigma_barn;   ///< cross section per atom (barn)
};

extern const KShellIonization kKShell[kElementCount];  ///< indexed Z - 1

/// Cross section per atom (barn) for an electron of kinetic energy `T_keV`.
inline double k_shell_sigma_barn(int Z, double T_keV) {
    if (Z < 1 || Z > static_cast<int>(kElementCount)) return 0.0;
    const KShellIonization& t = kKShell[Z - 1];
    if (T_keV <= t.energy_keV[0]) return 0.0;
    for (int i = 0; i + 1 < t.num_nodes; ++i) {
        if (T_keV <= t.energy_keV[i + 1]) {
            const double f = (T_keV - t.energy_keV[i])
                / (static_cast<double>(t.energy_keV[i + 1]) - t.energy_keV[i]);
            return t.sigma_barn[i] + f * (static_cast<double>(t.sigma_barn[i + 1]) - t.sigma_barn[i]);
        }
    }
    return t.sigma_barn[t.num_nodes - 1];
}

}  // namespace eedl_ionization
}  // namespace ceelo
