/// @file electron_elastic_data.h
/// @brief Electron elastic-scattering transport moments (EPICS2023 EEDL).
///
/// Generated by tools/prepare_cross_sections/generate_eedl_elastic.py from the
/// EEDL large-angle elastic cross section and angular distributions (MT=525),
/// for Z = 1..kMaxElectronTableZ on a log energy grid. Used by the detailed
/// electron walk (ElectronCsda::deposited_in_scoring_detailed), which fits a
/// Wentzel distribution to these two moments per material.

#include <cstddef>

namespace ceelo {
namespace eedl_elastic {

constexpr std::size_t kElementCount = 92;  ///< Z = 1..92 (electron-table domain)
constexpr std::size_t kEnergyCount = 36;   ///< log grid, 1 keV .. 20 MeV

/// Electron kinetic energy of each grid node (keV).
extern const float kEnergy_keV[kEnergyCount];

/// First transport cross section sigma_1 = integral (1 - cos theta) dsigma,
/// per atom (barn), indexed [Z - 1][energy node].
extern const float kSigma1_barn[kElementCount][kEnergyCount];

/// sigma_2 / sigma_1, with sigma_2 = integral (3/2)(1 - cos^2 theta) dsigma:
/// 3 for a forward delta, 1 for isotropic scattering.
extern const float kRatio21[kElementCount][kEnergyCount];

}  // namespace eedl_elastic
}  // namespace ceelo
