double erf_inv( const double z )
{
  if( (z < -1) || (z > 1) )
    throw std::domain_error( "erf_inv: argument outside range [-1, 1]" );
  if( z == 1 )
    throw std::overflow_error( "erf_inv: overflow" );
  if( z == -1 )
    throw std::overflow_error( "erf_inv: overflow" );
  if( z == 0 )
    return 0;

  // erf(-z) = -erf(z)
  double p, q, s;
  if( z < 0 )
  {
    p = -z;
    q = 1 - p;
    s = -1;
  }else
  {
    p = z;
    q = 1 - z;
    s = 1;
  }

  return s * erf_inv_imp( p, q );
}//double erf_inv( const double z )


double erfc_inv( const double z )
{
  if( (z < 0) || (z > 2) )
    throw std::domain_error( "erfc_inv: argument outside range [0, 2]" );
  if( z == 0 )
    throw std::overflow_error( "erfc_inv: overflow" );
  if( z == 2 )
    throw std::overflow_error( "erfc_inv: overflow" );

  // erfc(-z) = 2 - erfc(z)
  double p, q, s;
  if( z > 1 )
  {
    q = 2 - z;
    p = 1 - q;
    s = -1;
  }else
  {
    p = 1 - z;
    q = z;
    s = 1;
  }

  return s * erf_inv_imp( p, q );
}//double erfc_inv( const double z )


double normal_quantile( const double p )
{
  if( (p < 0) || (p > 1) || !std::isfinite( p ) )
    throw std::domain_error( "normal_quantile: probability outside [0, 1]" );

  return -erfc_inv( 2 * p ) * root_two;
}//double normal_quantile( const double p )


double poisson_quantile( const double mean, const double p )
{
  if( !(mean > 0) || !std::isfinite( mean ) )
    throw std::domain_error( "poisson_quantile: mean must be positive" );
  if( (p < 0) || (p > 1) || !std::isfinite( p ) )
    throw std::domain_error( "poisson_quantile: probability outside [0, 1]" );
  if( p == 0 )
    return 0;
  if( p == 1 )
    throw std::overflow_error( "poisson_quantile: overflow" );

  double pmf = std::exp( -mean ), cdf = pmf;
  if( p <= pmf )
    return 0;

  const double max_k = 10.0*mean + 1000.0;
  for( double k = 0; k < max_k; k += 1 )
  {
    const double next_pmf = pmf * mean / (k + 1);
    if( (p < 0.5) ? ((cdf + next_pmf) > p) : (cdf >= p) )
      return k;
    pmf = next_pmf;
    cdf += next_pmf;
  }

  throw std::runtime_error( "poisson_quantile: did not converge" );
}//double poisson_quantile(...)

