    if( mc_ratio > 0.0 )   mc_errs.push_back( std::fabs( mc_ratio - 1.0 ) );
    if( anc_ratio > 0.0 )  ancmc_errs.push_back( std::fabs( anc_ratio - 1.0 ) );
    if( et_ratio > 0.0 )   efftran_errs.push_back( std::fabs( et_ratio - 1.0 ) );

