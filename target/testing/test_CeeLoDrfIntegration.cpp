  const shared_ptr<ceelo::DetectorResponse> resp
        = CeeLoUtils::makeTransferResponse( gd, anchor, ceelo::AnchorCurve{}, "ANGLE-xfer" );
  BOOST_REQUIRE( resp );

  // Sample disk: r=1.725 cm, half-length 1.0 cm, bottom 0.113 cm off the
