/** Validation of the CeeLo Monte-Carlo-parameterized detector response as
 integrated into DetectorPeakResponse.

 Uses PRE-COMPUTED fixtures in test_data/ceelo_drf/ (golden response XMLs +
 fresh MC probe banks, generated by CeeLo's `make_golden_response` tool with
 fixed seeds) - the tests themselves never run Monte Carlo.  To regenerate
 the fixtures (e.g. after a CeeLo physics change), configure the tests with
 -DINTERSPEC_REGEN_CEELO_GOLDENS=ON and build the `regen_ceelo_goldens`
 target (takes several minutes of MC), or run `make_golden_response`
 directly.

 The accuracy gates trace to the July 2026 parameterization campaign
 (response_function_spec.md sec 4/5 in the CeeLo dev repo): probe-bank FEP
 error medians of a fraction of a percent with few-percent 95th percentiles,
 and honestly-covering uncertainties.
 */

