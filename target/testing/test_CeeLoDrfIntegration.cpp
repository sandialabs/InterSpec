  const double e_above = det2->fepEfficiencyEval( static_cast<float>(1.005*edge), 0.0, 0.0, dist ).value;
  BOOST_REQUIRE_GT( e_below1, 0.0 );
  BOOST_REQUIRE_GT( e_below2, 0.0 );
