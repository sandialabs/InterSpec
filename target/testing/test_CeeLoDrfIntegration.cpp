/** The assembled parameterization must reproduce fresh, never-fitted MC
 probe points (campaign spec sec 4: FEP median a fraction of a percent, 95th
 a few percent).  Gates here include headroom over the campaign numbers so
 normal MC-noise variation in regenerated fixtures does not flake the test.
 */
BOOST_AUTO_TEST_CASE( probe_bank_nai3x3 )
{
  // High-stats fixture (0.1% node precision): FEP median ~0.6%, 95th ~2.6%.
  check_probe_bank( "nai3x3", 0.015, 0.045 );
}

BOOST_AUTO_TEST_CASE( probe_bank_hpge_coax )
{
  // HPGe is the steepest eta(theta) detector. The tabulated near-field model
  //  (ln N on a cos_theta x d grid, PCHIP-interpolated, covering to the eta
  //  grazing edge cos_theta=0.02) brought FEP 95th to ~1% and max to ~4%
  //  (was ~5% 95th / ~11% max with the old quadratic near-field surface).
  //  The p95 gate is bounded below by the TOT tier (eta_tot, unaffected by the
  //  near-field model), whose 95th is ~6.7%: TOT is checked at 2*p95_gate, so
  //  p95_gate stays >= ~0.05 to keep ~50% headroom there.
  check_probe_bank( "hpge_coax", 0.015, 0.05 );
}

BOOST_AUTO_TEST_CASE( probe_bank_czt_box )
{
  // High-stats fixture (0.15%): FEP median ~0.35%, 95th ~2.3%.
  check_probe_bank( "czt_box", 0.015, 0.045 );
}


/** DrfExtra (database column) round trip: DRF -> DrfExtra string -> DRF must
 preserve the MC response bit-for-bit (content hash) and evaluate identically.
 */
BOOST_AUTO_TEST_CASE( drf_extra_round_trip )
{
  shared_ptr<DetectorPeakResponse> drf = drf_with_golden( "nai3x3" );

  const string extra = drf->drfExtraToXmlString();
  BOOST_REQUIRE( !extra.empty() );

  auto drf2 = make_shared<DetectorPeakResponse>( *drf );
  drf2->setDrfExtraFromXmlString( extra );

  BOOST_REQUIRE( drf2->ceeloResponse() );
  BOOST_CHECK_EQUAL( drf->ceeloResponse()->content_hash(),
                     drf2->ceeloResponse()->content_hash() );

  for( const double E : {60.0, 121.8, 661.7, 2614.0} )
  {
    const DetectorPeakResponse::EffEval a
                = drf->fepEfficiencyEval( E, 0.3, 0.0, 30.0*PhysicalUnits::cm );
    const DetectorPeakResponse::EffEval b
                = drf2->fepEfficiencyEval( E, 0.3, 0.0, 30.0*PhysicalUnits::cm );
    BOOST_CHECK_CLOSE( a.value, b.value, 1.0E-9 );
    BOOST_CHECK_CLOSE( a.sigma, b.sigma, 1.0E-9 );
  }
}//drf_extra_round_trip


/** Legacy DRFs (no MC response) must evaluate bit-identically through the
 old entry points, and the new Eval API must wrap them faithfully.
 */
BOOST_AUTO_TEST_CASE( legacy_drf_untouched )
{
  auto det = make_shared<DetectorPeakResponse>( "legacy", "" );
  const string fcn = "exp(-343.6330974237 + 269.1023287277*log(x)"
                     "+ -83.8077567526*log(x)^2  + 12.9980559362*log(x)^3"
                     "+ -1.0068649823*log(x)^4 + 0.0311640084*log(x)^5)";
  det->setIntrinsicEfficiencyFormula( fcn, 2.2*PhysicalUnits::cm,
                    PhysicalUnits::keV, 0.0f, 0.0f,
                    DetectorPeakResponse::EffGeometryType::FarFieldIntrinsic );

  //The documented golden values (DetectorPeakResponse.h header comment).
  BOOST_CHECK_CLOSE( det->intrinsicEfficiency(121.78f), 0.625191, 0.01 );
  BOOST_CHECK_CLOSE( det->intrinsicEfficiency(411.02f), 0.333307, 0.01 );
  BOOST_CHECK_CLOSE( det->intrinsicEfficiency(700.0f), 0.219004, 0.01 );

  //The Eval API must be bit-identical to the legacy call for legacy DRFs.
  for( const float E : {121.78f, 411.02f, 700.0f} )
  {
    const DetectorPeakResponse::EffEval eval = det->intrinsicEfficiencyEval( E );
    BOOST_CHECK_EQUAL( eval.value, static_cast<double>(det->intrinsicEfficiency(E)) );
    BOOST_CHECK_EQUAL( eval.sigma, 0.0 );  //no uncertainty info attached
    BOOST_CHECK( eval.flag == DetectorPeakResponse::EffFlag::Ok );

    const double dist = 25.0 * PhysicalUnits::cm;
    const DetectorPeakResponse::EffEval abs_eval = det->efficiencyEval( E, dist );
    BOOST_CHECK_EQUAL( abs_eval.value, det->efficiency( E, dist ) );
  }

  //Off-axis queries on a legacy DRF are flagged (the curve cant model them).
  const DetectorPeakResponse::EffEval off
          = det->fepEfficiencyEval( 661.7f, 0.5, 0.0, 25.0*PhysicalUnits::cm );
  BOOST_CHECK( off.flag == DetectorPeakResponse::EffFlag::NeedsMc );

  //No total-efficiency info -> flagged, zero value.
  const DetectorPeakResponse::EffEval tot
          = det->totalEfficiencyEval( 661.7f, 0.0, 0.0, 25.0*PhysicalUnits::cm );
  BOOST_CHECK( tot.flag == DetectorPeakResponse::EffFlag::NeedsMc );
  BOOST_CHECK_EQUAL( tot.value, 0.0 );
}//legacy_drf_untouched


/** Provenance flags surface through the DetectorPeakResponse dispatch. */
BOOST_AUTO_TEST_CASE( flags_surface_through_drf )
{
  shared_ptr<DetectorPeakResponse> drf = drf_with_golden( "czt_box" );  //far-field profile
  const shared_ptr<const ceelo::DetectorResponse> resp = drf->ceeloResponse();
  BOOST_REQUIRE_GT( resp->provenance.min_distance_cm, 0.0 );

  //Inside the far-field profiles validity floor -> NearFieldUnmodeled.
  const DetectorPeakResponse::EffEval close = drf->fepEfficiencyEval( 661.7f, 0.0, 0.0,
                                  0.25*resp->provenance.min_distance_cm*PhysicalUnits::cm );
  BOOST_CHECK( close.flag == DetectorPeakResponse::EffFlag::NearFieldUnmodeled );

  //Outside the validated energy range -> clamped.
  const DetectorPeakResponse::EffEval low_e = drf->fepEfficiencyEval( 10.0f, 0.0, 0.0,
                                                            30.0*PhysicalUnits::cm );
  BOOST_CHECK( low_e.flag == DetectorPeakResponse::EffFlag::OutOfRangeClamped );

  //Well within range and distance -> Ok.
  const DetectorPeakResponse::EffEval ok = drf->fepEfficiencyEval( 661.7f, 0.0, 0.0,
                                                          30.0*PhysicalUnits::cm );
  BOOST_CHECK( ok.flag == DetectorPeakResponse::EffFlag::Ok );
}//flags_surface_through_drf


/** The multi-energy covariance the Activity/Shielding fit will consume:
 symmetric, positive-diagonal, strongly correlated between nearby energies.
 */
BOOST_AUTO_TEST_CASE( efficiency_covariance_structure )
{
  shared_ptr<DetectorPeakResponse> drf = drf_with_golden( "hpge_coax" );

  const vector<double> energies{ 121.78, 344.28, 661.66, 1173.23, 1408.01 };
  const vector<double> cov = drf->efficiencyFracCovariance( energies, 0.0,
                                                            50.0*PhysicalUnits::cm );
  const size_t n = energies.size();
  BOOST_REQUIRE_EQUAL( cov.size(), n*n );

  for( size_t i = 0; i < n; ++i )
  {
    BOOST_CHECK_GT( cov[i*n+i], 0.0 );
    for( size_t j = 0; j < n; ++j )
    {
      BOOST_CHECK_CLOSE( cov[i*n+j], cov[j*n+i], 1.0E-9 );
      const double rho = cov[i*n+j] / std::sqrt( cov[i*n+i]*cov[j*n+j] );
      BOOST_CHECK_LE( std::fabs(rho), 1.0 + 1.0E-9 );
      if( i != j )
        BOOST_CHECK_GT( rho, 0.2 );  //model floors/transfer are common-mode
    }
  }

  //Covariance must grow off-axis / close-in (sigma_transfer) when grounded;
  //  ungrounded fixtures still must not SHRINK off-axis.
  const vector<double> cov_off = drf->efficiencyFracCovariance( energies, 1.2,
                                                            5.0*PhysicalUnits::cm );
  BOOST_CHECK_GE( cov_off[0] + 1.0E-12, cov[0] );
}//efficiency_covariance_structure


/** MeasuredDrfPoints: covariance structure (stat diagonal + per-source
 certificate blocks) and XML round trip.
 */
BOOST_AUTO_TEST_CASE( measured_points_covariance )
{
  vector<MeasuredEffPoint> pts;
  for( const double E : {121.78, 344.28, 778.9, 1408.01} )
  {
    MeasuredEffPoint p;
    p.energy = static_cast<float>( E );
    p.efficiency = 1.0E-3f;
    p.fracStatUncert = 0.01f;
    p.fracCertUncert = 0.03f;
    p.sourceKey = "Eu152#0";
    p.distance = static_cast<float>( 25.0 * PhysicalUnits::cm );
    pts.push_back( p );
  }
  {
    MeasuredEffPoint p;
    p.energy = 661.66f;
    p.efficiency = 8.0E-4f;
    p.fracStatUncert = 0.005f;
    p.fracCertUncert = 0.02f;
    p.sourceKey = "Cs137#1";
    p.distance = static_cast<float>( 25.0 * PhysicalUnits::cm );
    pts.push_back( p );
  }

  auto points = make_shared<MeasuredDrfPoints>();
  points->setPoints( pts );

  const shared_ptr<DetectorEfficiencyUncert> uncert = points->toEfficiencyUncert();
  BOOST_REQUIRE( uncert );

  const vector<double> energies{ 121.78, 344.28, 661.66 };
  const vector<double> cov = uncert->efficiencyFracCovariance( energies );
  BOOST_REQUIRE_EQUAL( cov.size(), 9u );

  //Same source (121.78, 344.28): certificate block -> covariance ~ 0.03^2.
  BOOST_CHECK_CLOSE( cov[0*3+1], 0.03*0.03, 10.0 );
  //Var(121.78) = stat^2 + cert^2.
  BOOST_CHECK_CLOSE( cov[0*3+0], 0.01*0.01 + 0.03*0.03, 10.0 );
  //Different sources: nodes are independent - but the covariance of the
  //  in-between query energies is interpolated, so just check it is much
  //  smaller than the same-source block.
  BOOST_CHECK_LT( std::fabs(cov[0*3+2]), 0.5*cov[0*3+1] );

  //XML round trip preserves everything.
  rapidxml::xml_document<char> doc;
  points->toXml( &doc, &doc );
  auto points2 = make_shared<MeasuredDrfPoints>();
  points2->fromXml( doc.first_node("MeasuredEffPoints") );
  BOOST_REQUIRE_EQUAL( points2->points().size(), points->points().size() );
#if( PERFORM_DEVELOPER_CHECKS )
  BOOST_CHECK_NO_THROW( MeasuredDrfPoints::equalEnough( *points, *points2 ) );
#endif
}//measured_points_covariance
