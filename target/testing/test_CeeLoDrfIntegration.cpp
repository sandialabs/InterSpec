    BOOST_TEST_MESSAGE( "absolute MC vs ANGLE |ratio-1|: median=" << 100.0*mc_errs[mc_errs.size()/2]
                        << "%  max=" << 100.0*mc_errs.back() << "%  (n=" << mc_errs.size() << ")" );
