  struct ProbeRow
  {
    double energy_keV, d_cm, cos_theta, phi_deg;
    double eps_fep, fep_unc, eps_tot, tot_unc;
  };//struct ProbeRow


  string fixture_path( const string &leaf )
  {
    return SpecUtils::append_path( SpecUtils::append_path( g_test_data_dir, "ceelo_drf" ), leaf );
  }


  string read_file( const string &path )
  {
    ifstream f( path.c_str(), ios::in | ios::binary );
    BOOST_REQUIRE_MESSAGE( f.is_open(), "Failed to open fixture '" + path + "'" );
    stringstream strm;
    strm << f.rdbuf();
    return strm.str();
  }


  vector<ProbeRow> read_probe_bank( const string &path )
  {
    ifstream f( path.c_str() );
    BOOST_REQUIRE_MESSAGE( f.is_open(), "Failed to open probe bank '" + path + "'" );

    vector<ProbeRow> rows;
    string line;
    while( std::getline( f, line ) )
    {
      if( line.empty() || (line[0] == '#') || (line.rfind("point,",0) == 0) )
        continue;

      // point,E_keV,d_cm,cos_theta,phi_deg,eps_fep,fep_unc,eps_tot,tot_unc,seed
      vector<double> fields;
      stringstream strm( line );
      string field;
      while( std::getline( strm, field, ',' ) )
        fields.push_back( std::stod(field) );
      if( fields.size() < 9 )
        continue;

      ProbeRow r;
      r.energy_keV = fields[1];
      r.d_cm = fields[2];
      r.cos_theta = fields[3];
      r.phi_deg = fields[4];
      r.eps_fep = fields[5];
      r.fep_unc = fields[6];
      r.eps_tot = fields[7];
      r.tot_unc = fields[8];
      rows.push_back( r );
    }//while( getline )

    return rows;
  }//read_probe_bank(...)


  /** Loads a golden response through the DetectorPeakResponse DrfExtra path
   (i.e., the same code path the database and DRF XML use).
   */
  shared_ptr<DetectorPeakResponse> drf_with_golden( const string &preset )
  {
    const string xml = read_file( fixture_path( preset + "_response.xml" ) );

    auto drf = make_shared<DetectorPeakResponse>( preset, "golden fixture" );
    drf->setIntrinsicEfficiencyFormula( "1.0", 5.0*PhysicalUnits::cm,
                    PhysicalUnits::keV, 0.0f, 0.0f,
                    DetectorPeakResponse::EffGeometryType::FarFieldIntrinsic );
    drf->setCeeloResponse( ceelo::DetectorResponse::from_xml_string( xml ) );

    BOOST_REQUIRE( drf->ceeloResponse() );
    return drf;
  }//drf_with_golden(...)


  struct BankStats
  {
    size_t n = 0;
    double median = 0.0, p95 = 0.0, max_err = 0.0;
    double cov_1sig = 0.0, frac_gt_3sig = 0.0;
  };//struct BankStats

  BankStats score_bank( const shared_ptr<DetectorPeakResponse> &drf,
                        const vector<ProbeRow> &bank, const bool fep )
  {
    const shared_ptr<const ceelo::DetectorResponse> resp = drf->ceeloResponse();
    const double min_dist_cm = resp->provenance.min_distance_cm;

    vector<double> errs, pulls;
    for( const ProbeRow &row : bank )
    {
      const double mc = fep ? row.eps_fep : row.eps_tot;
      const double mc_sig = fep ? row.fep_unc : row.tot_unc;
      if( (mc <= 0.0) || ((mc_sig/mc) > 0.05) )
        continue;  //probe didnt converge well enough to score against

      // Below the profiles validity floor the response *flags* rather than
      //  promises accuracy - dont score those (the flag test covers them).
      if( row.d_cm < min_dist_cm )
        continue;

      const double theta = std::acos( std::min( std::max(row.cos_theta,-1.0), 1.0 ) );
      const double phi = row.phi_deg * M_PI / 180.0;
      const double dist = row.d_cm * PhysicalUnits::cm;

      // The probe banks measure d from the crystal-face origin; evaluate
      //  through the ceelo response directly at that position so reference
      //  point conventions cant skew the comparison.
      const Eigen::Vector3d pos = ceelo::source_position( row.d_cm, row.cos_theta, phi );
      const ceelo::EffResult res = fep ? resp->eps_fep_at( row.energy_keV, pos )
                                       : resp->eps_total_at( row.energy_keV, pos );

      // Cross-check the DetectorPeakResponse dispatch agrees with the direct
      //  evaluation when the reference point is the crystal face.
      if( fep && (resp->descriptor.reference_point == ceelo::ReferencePoint::CrystalFace) )
      {
        //(theta -> position round trip costs a few ULP; 1e-4 percent = 1e-6 relative)
        const DetectorPeakResponse::EffEval through_drf
                        = drf->fepEfficiencyEval( row.energy_keV, theta, phi, dist );
        BOOST_CHECK_CLOSE( through_drf.value, res.value, 1.0E-4 );
      }

      const double rel = res.value/mc - 1.0;
      errs.push_back( std::fabs(rel) );

      const double sig_tot = std::sqrt( std::pow(res.sigma/std::max(res.value,1e-300),2.0)
                                        + std::pow(mc_sig/mc,2.0) );
      pulls.push_back( std::fabs(rel) / std::max(sig_tot,1e-12) );
    }//for( const ProbeRow &row : bank )

    BankStats stats;
    stats.n = errs.size();
    if( errs.empty() )
      return stats;

    std::sort( begin(errs), end(errs) );
    stats.median = errs[errs.size()/2];
    stats.p95 = errs[static_cast<size_t>(0.95*(errs.size()-1))];
    stats.max_err = errs.back();
    stats.cov_1sig = std::count_if( begin(pulls), end(pulls),
                            [](double p){ return p <= 1.0; } ) / double(pulls.size());
    stats.frac_gt_3sig = std::count_if( begin(pulls), end(pulls),
                            [](double p){ return p > 3.0; } ) / double(pulls.size());
    return stats;
  }//score_bank(...)


  void check_probe_bank( const string &preset, const double median_gate,
                         const double p95_gate )
  {
    shared_ptr<DetectorPeakResponse> drf = drf_with_golden( preset );
    const vector<ProbeRow> bank = read_probe_bank( fixture_path( preset + "_probe.csv" ) );
    BOOST_REQUIRE_GT( bank.size(), 20u );

    const BankStats fep = score_bank( drf, bank, true );
    BOOST_TEST_MESSAGE( preset << " FEP: n=" << fep.n
                        << " median=" << 100.0*fep.median << "%"
                        << " 95th=" << 100.0*fep.p95 << "%"
                        << " max=" << 100.0*fep.max_err << "%"
                        << " cov(1s)=" << 100.0*fep.cov_1sig << "%"
                        << " >3s=" << 100.0*fep.frac_gt_3sig << "%" );

    BOOST_REQUIRE_GT( fep.n, 15u );
    BOOST_CHECK_LT( fep.median, median_gate );
    BOOST_CHECK_LT( fep.p95, p95_gate );
    //Coverage: honest sigmas - most probes within 1 sigma, almost none past 3.
    BOOST_CHECK_GT( fep.cov_1sig, 0.5 );
    BOOST_CHECK_LT( fep.frac_gt_3sig, 0.101 );

    const BankStats tot = score_bank( drf, bank, false );
    BOOST_TEST_MESSAGE( preset << " TOT: n=" << tot.n
                        << " median=" << 100.0*tot.median << "%"
                        << " 95th=" << 100.0*tot.p95 << "%" );
    BOOST_REQUIRE_GT( tot.n, 15u );
    BOOST_CHECK_LT( tot.median, 2.0*median_gate );
    BOOST_CHECK_LT( tot.p95, 2.0*p95_gate );
  }//check_probe_bank(...)
